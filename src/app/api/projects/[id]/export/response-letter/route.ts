import { NextRequest, NextResponse } from "next/server";
import {
  AlignmentType,
  Document,
  HeadingLevel,
  Packer,
  Paragraph,
  TextRun,
} from "docx";
import { getApiContext } from "@/lib/auth";
import type { Project, ResponseThread } from "@/lib/types";

/**
 * 组装完整 Response Letter(.docx):
 * 按 Reviewer 分组,Comment(斜体灰)+ Response(打磨稿优先,退回草稿)。
 * 只有写了草稿或已打磨的线程才进入信件。
 */
export async function GET(_req: NextRequest, ctx: { params: Promise<{ id: string }> }) {
  const actx = await getApiContext();
  if (!actx.ok) return actx.res;
  const { id } = await ctx.params;
  const project = await actx.ctx.store.get(actx.ctx.userId, id);
  if (!project) return NextResponse.json({ error: "项目不存在" }, { status: 404 });

  const threads = project.responses ?? [];
  const usable = threads.filter((t) => t.polished.trim() || t.draft.trim());
  if (usable.length === 0) {
    return NextResponse.json({ error: "暂无可导出的回复内容(请先撰写草稿或打磨)" }, { status: 400 });
  }

  // 按 reviews 数组中的审稿人顺序分组;组内 Major 优先、编号升序
  const reviewerOrder = project.reviews?.map((r) => r.label) ?? [...new Set(usable.map((t) => t.reviewer))];
  const rank = (t: ResponseThread) => {
    const reviewerIdx = reviewerOrder.indexOf(t.reviewer);
    const num = Number(t.commentId.split("-").pop()) || 0;
    return [reviewerIdx < 0 ? 99 : reviewerIdx, t.type === "major" ? 0 : 1, num];
  };
  const sorted = [...usable].sort((a, b) => {
    const [ra, ta, na] = rank(a);
    const [rb, tb, nb] = rank(b);
    return ra - rb || ta - tb || na - nb;
  });

  const children: Paragraph[] = [
    new Paragraph({ text: "Response to Reviewers", heading: HeadingLevel.TITLE, alignment: AlignmentType.CENTER }),
    new Paragraph({ children: [new TextRun({ text: `Manuscript: ${project.title}`, bold: true })] }),
  ];
  if (project.meta.targetJournal) {
    children.push(new Paragraph({ children: [new TextRun(`Target journal: ${project.meta.targetJournal}`)] }));
  }
  children.push(
    new Paragraph({ children: [new TextRun(`Date: ${new Date().toLocaleDateString("en-US")}`)] }),
    new Paragraph({
      children: [
        new TextRun(
          "We sincerely thank the editor and the reviewers for the constructive and insightful comments, which have helped us substantially improve the manuscript. Point-by-point responses are provided below; all changes in the revised manuscript are highlighted.",
        ),
      ],
      spacing: { after: 300 },
    }),
  );

  let currentReviewer = "";
  for (const t of sorted) {
    if (t.reviewer !== currentReviewer) {
      currentReviewer = t.reviewer;
      children.push(new Paragraph({ text: `Response to ${t.reviewer}`, heading: HeadingLevel.HEADING_1 }));
    }
    children.push(
      new Paragraph({
        children: [
          new TextRun({ text: "Comment: ", bold: true, color: "555555" }),
          new TextRun({ text: t.commentText, italics: true, color: "555555" }),
        ],
        spacing: { before: 240, after: 80 },
      }),
      new Paragraph({
        children: [
          new TextRun({ text: "Response: ", bold: true }),
          new TextRun({ text: t.polished.trim() || t.draft.trim() }),
        ],
        spacing: { after: 160 },
      }),
    );
  }
  children.push(
    new Paragraph({
      children: [new TextRun({ text: "Generated by R&R Studio", size: 16, color: "999999" })],
      spacing: { before: 480 },
      alignment: AlignmentType.CENTER,
    }),
  );

  const doc = new Document({ sections: [{ children }] });
  const buf = await Packer.toBuffer(doc);
  return docResponse(buf, `response-letter-${id.slice(0, 8)}.docx`);
}

function docResponse(buf: Buffer, filename: string) {
  return new NextResponse(new Uint8Array(buf), {
    headers: {
      "Content-Type": "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
      "Content-Disposition": `attachment; filename="${filename}"`,
      "Cache-Control": "no-store",
    },
  });
}

export type { Project };
