import { NextRequest, NextResponse } from "next/server";
import {
  AlignmentType,
  Document,
  HeadingLevel,
  Packer,
  Paragraph,
  TextRun,
} from "docx";
import { getApiContext } from "@/lib/auth";
import type { CritiqueItem } from "@/lib/types";

const SEVERITY_LABEL: Record<string, string> = { major: "Major", minor: "Minor", suggestion: "建议" };
const CATEGORY_LABEL: Record<string, string> = { logic: "逻辑", expression: "表达", grammar: "语法", style: "风格" };

/** 导出 Critique 报告(.docx),按章节分组,已采纳条目带 ✓ 标记 */
export async function GET(_req: NextRequest, ctx: { params: Promise<{ id: string }> }) {
  const actx = await getApiContext();
  if (!actx.ok) return actx.res;
  const { id } = await ctx.params;
  const project = await actx.ctx.store.get(actx.ctx.userId, id);
  if (!project) return NextResponse.json({ error: "项目不存在" }, { status: 404 });
  if (!project.critique || project.critique.items.length === 0) {
    return NextResponse.json({ error: "尚未生成 Critique 报告" }, { status: 400 });
  }

  const items = project.critique.items;
  const sections = [...new Set(items.map((i) => i.section))];
  const count = (s: CritiqueItem["severity"]) => items.filter((i) => i.severity === s).length;

  const children: Paragraph[] = [
    new Paragraph({ text: "Critique Report", heading: HeadingLevel.TITLE, alignment: AlignmentType.CENTER }),
    new Paragraph({ children: [new TextRun({ text: project.title, bold: true })] }),
    new Paragraph({
      children: [
        new TextRun(
          `${project.meta.targetJournal ? `目标期刊: ${project.meta.targetJournal} · ` : ""}生成时间: ${new Date(project.critique.createdAt).toLocaleString("zh-CN")} · 共 ${items.length} 条(Major ${count("major")} / Minor ${count("minor")} / 建议 ${count("suggestion")})`,
        ),
      ],
      spacing: { after: 240 },
    }),
  ];

  for (const section of sections) {
    children.push(new Paragraph({ text: section, heading: HeadingLevel.HEADING_1 }));
    for (const item of items.filter((i) => i.section === section)) {
      children.push(
        new Paragraph({
          children: [
            new TextRun({
              text: `${item.adopted ? "✓ " : ""}[${SEVERITY_LABEL[item.severity]} · ${CATEGORY_LABEL[item.category] ?? item.category}] `,
              bold: true,
            }),
            new TextRun({ text: `“${item.quote}”`, italics: true, color: "666666" }),
          ],
          spacing: { before: 200, after: 60 },
        }),
        new Paragraph({ children: [new TextRun({ text: item.comment })], spacing: { after: 60 } }),
        new Paragraph({
          children: [
            new TextRun({ text: "建议: ", bold: true, color: "4F46E5" }),
            new TextRun({ text: item.suggestion, color: "4F46E5" }),
          ],
          spacing: { after: 120 },
        }),
      );
    }
  }
  children.push(
    new Paragraph({
      children: [new TextRun({ text: "Generated by R&R Studio", size: 16, color: "999999" })],
      spacing: { before: 480 },
      alignment: AlignmentType.CENTER,
    }),
  );

  const doc = new Document({ sections: [{ children }] });
  const buf = await Packer.toBuffer(doc);
  return new NextResponse(new Uint8Array(buf), {
    headers: {
      "Content-Type": "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
      "Content-Disposition": `attachment; filename="critique-report-${id.slice(0, 8)}.docx"`,
      "Cache-Control": "no-store",
    },
  });
}
